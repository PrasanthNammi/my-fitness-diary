// Fills the exercise-groups block of database/mcp-connector-v2.sql from the app's bundled
// catalogues (exercise name -> broad muscle group). Re-run after the catalogues change.
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..'), file = path.join(root, 'database/mcp-connector-v2.sql');
const groups = new Map();
for (const source of ['free', 'wger']) for (const e of require(path.join(root, `public/legacy/data/${source}-exercises.json`))) {
  const name = String(e.name || '').trim().toLowerCase().replace(/\s+/g, ' ');
  if (name && ['Chest', 'Back', 'Shoulders', 'Arms', 'Legs', 'Core'].includes(e.muscle) && !groups.has(name)) groups.set(name, e.muscle);
}
const rows = [...groups].sort(([a], [b]) => a.localeCompare(b)).map(([n, g]) => `('${n.replace(/'/g, "''")}','${g}')`);
const block = `-- BEGIN exercise groups (generated by scripts/gen-exercise-groups.cjs; do not edit by hand)
insert into mfd_mcp.exercise_groups(name,grp) values
${rows.join(',\n')}
on conflict(name) do update set grp=excluded.grp;
-- END exercise groups`;
const sql = fs.readFileSync(file, 'utf8');
const next = sql.replace(/-- BEGIN exercise groups[\s\S]*?-- END exercise groups/, block);
if (next === sql && !sql.includes(block)) throw Error('exercise groups markers not found');
fs.writeFileSync(file, next);
console.log(`exercise groups: ${rows.length}`);
