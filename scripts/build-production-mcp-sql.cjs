// Builds database/production/mcp-production.sql: the AI connector database setup for a
// project that has none yet, from the same tested files staging/sandbox use, as ONE
// transaction (all or nothing). Usage: node scripts/build-production-mcp-sql.cjs <connector origin>
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..');
const origin = process.argv[2] || 'https://mfd-connect.shanustylish777.workers.dev';
if (!/^https:\/\/[a-z0-9.-]+$/.test(origin)) throw Error('connector origin like https://name.example.workers.dev');
const part = file => fs.readFileSync(path.join(root, file), 'utf8')
  .split('\n').filter(line => !/^\s*(begin|commit);\s*$/i.test(line)).join('\n');
const sql = `-- AI connector database setup for PRODUCTION (generated by scripts/build-production-mcp-sql.cjs).
-- Sources: database/mcp.sql, database/mcp-connector-proxy.sql, database/mcp-connector-v2.sql,
-- plus staging's OAuth guard on mfd_observability.record_sync. One transaction: on any error
-- nothing is applied. Adds only the mfd_mcp schema, OAuth-token restrictions and the connector
-- functions; does not change any diary, profile or social data.
-- Connector: ${origin}
begin;
${part('database/mcp.sql')}

-- Same OAuth-token guard as staging: connector tokens cannot record sync metrics.
create or replace function mfd_observability.record_sync(outcome text, elapsed double precision)
 returns void language plpgsql security definer set search_path to '' as $function$
begin
 if auth.uid() is null or auth.jwt()->>'client_id' is not null then raise exception 'Sign in required' using errcode='42501'; end if;
 if outcome not in ('saved','conflict') or elapsed<0 or elapsed>600 then raise exception 'Invalid metric'; end if;
 update mfd_observability.sync_totals t set total=t.total+1,seconds_total=t.seconds_total+elapsed,last_at=clock_timestamp() where t.outcome=record_sync.outcome;
end $function$;

${part('database/mcp-connector-proxy.sql')}
${part('database/mcp-connector-v2.sql')}

-- Production connector address and add-only writes (the AI never edits or deletes).
alter table mfd_mcp.settings alter column resource_uri set default '${origin}/mcp';
update mfd_mcp.settings set resource_uri='${origin}/mcp', writes_enabled=true where id;
commit;
`;
const out = path.join(root, 'database/production/mcp-production.sql');
fs.mkdirSync(path.dirname(out), {recursive: true});
fs.writeFileSync(out, sql);
console.log(`${path.relative(root, out)}: ${sql.length} bytes for ${origin}`);
