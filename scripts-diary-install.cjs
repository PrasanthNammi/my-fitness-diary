// Writes the REAL install of the MFD 3.0 database (database/diary/01–11) as numbered files in ~/Downloads/mfd-db-install/,
// each small enough for the Supabase SQL editor (the full exercise library alone is ~1.9 MB).
//
//   1-tables.sql        every table, the follow triggers, the library's linking fields, then fills every diary once
//                       and ends with the old-vs-new report (all lines should say OK).
//   2…N-library-*.sql   the rest of the exercise library (texts, muscles, equipment), in pieces.
//
// Run them in number order. Each runs in one transaction (all or nothing) and is safe to run again.
// The end state is the same as running 01–11 in order (tests/diary-install.cjs checks that).
// Usage: node scripts-diary-install.cjs [out-dir]
const fs = require('fs'), os = require('os'), path = require('path');
const compare = require('./scripts-diary-report.cjs');
const LIMIT = 240 * 1024;
const q = (v) => (v == null ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const strip = (sql) => sql.split('\n').filter((l) => !/^\s*(begin|commit);\s*$/i.test(l)).join('\n');
const part = (f) => strip(fs.readFileSync(path.join(__dirname, 'database/diary', f + '.sql'), 'utf8'));
const cat = JSON.parse(fs.readFileSync(path.join(__dirname, 'public/catalogue/mfd_exercises.json'), 'utf8'));

// Split 04-catalogue.sql into its statements: the small lists, the exercises, and the three link lists.
const lines = fs.readFileSync(path.join(__dirname, 'database/diary/04-catalogue.sql'), 'utf8').split('\n');
const at = (re, from = 0) => { const i = lines.findIndex((l, k) => k >= from && re.test(l)); if (i < 0) throw new Error('04-catalogue.sql: ' + re); return i; };
const exStart = at(/^insert into diary\.exercises /), exEnd = at(/^on conflict \(source, source_ref\)/, exStart);
const exTailEnd = at(/;\s*$/, exEnd);
const lists = lines.slice(at(/^insert into diary\.muscle_groups /), exStart).join('\n').trim();
const rows = (a, b) => lines.slice(a, b).map((l) => l.replace(/,\s*$/, ''));
const exHead = lines[exStart], exRows = rows(exStart + 1, exEnd), exTail = lines.slice(exEnd, exTailEnd + 1).join('\n');
const links = ['exercise_muscle_groups', 'exercise_muscles', 'exercise_equipment'].map((t) => {
  const h = at(new RegExp(`^insert into diary\\.${t} \\(`)), e = at(/^on conflict do nothing;/, h);
  const cols = lines[h].match(/\(([^)]*)\)/)[1].split(',').map((c) => c.trim());
  // (md5('mfd:' || 'ref')::uuid, 'a', 'b')  →  ('ref', 'a', 'b'): the id is worked out once in the insert.
  const rs = rows(h + 1, e).map((r) => {
    const m = r.match(/^\(md5\('mfd:' \|\| ('(?:[^']|'')*')\)::uuid, (.*)$/);
    if (!m) throw new Error('unexpected link row: ' + r);
    return `(${m[1]}, ${m[2]}`;
  });
  return { t, cols, rs };
});
if (exRows.length !== cat.exercises.length) throw new Error(`04-catalogue.sql has ${exRows.length} exercises, catalogue ${cat.exercises.length}`);

const lite = `-- Library: the linking fields of every built-in exercise (texts, muscles and equipment follow in the next files).
insert into diary.exercises (id, source, source_ref, name, tracking) values
${cat.exercises.map((e) => `(md5('mfd:' || ${q(e.id)})::uuid, 'mfd', ${q(e.id)}, ${q(e.name)}, ${q(e.tracking)})`).join(',\n')}
on conflict do nothing;`;

const wrap = (title, body) => `-- MFD 3.0 database, REAL INSTALL · ${title}
-- Generated by scripts-diary-install.cjs from database/diary/01–11. Run the files in number order in the Supabase SQL
-- editor (project Forma). Each one is all-or-nothing and safe to run again; the app keeps working on the old data.
begin;
${body}
commit;
`;

const files = [];
files.push(['1-tables', wrap('file 1: tables, follow triggers, first fill', `${part('01-foundation')}
${part('02-library')}
${lists}
${lite}
${part('03-training')}
${part('05-fill-training')}
${part('06-nutrition')}
${part('07-fill-nutrition')}
${part('08-body')}
${part('09-fill-body')}
${part('10-account')}
${part('11-fill-account')}
-- First fill: every diary once. From now on the follow triggers keep the tables in step with every save.
do $fill$ declare u uuid; begin
  for u in select user_id from public.forma_workspaces loop
    perform diary.fill_training(u); perform diary.fill_nutrition(u); perform diary.fill_body(u); perform diary.fill_account(u);
  end loop;
end $fill$;
-- The report: every line should say OK. "problems" lists values the new rules left out (expected: none).
select area, item, old_value as old, new_value as new, case when old_value = new_value then 'OK' else 'DIFFERENT' end as result
from (${compare}
) r(k, area, item, old_value, new_value)
union all select 'Check', 'problems', null, (select count(*) from diary.fill_problems), case when exists (select 1 from diary.fill_problems) then 'LOOK' else 'OK' end;`)]);

// Library pieces: exercise texts, then the links. On a fresh install there are no old links to clear, so every
// piece only adds and can be run again on its own.
const chunks = (items, render, overhead) => {
  // As few files as fit under LIMIT, with the items spread evenly over them.
  const total = items.reduce((n, it) => n + it.length + 2, 0);
  const target = total / Math.ceil(total / (LIMIT - overhead));
  const out = []; let cur = [], size = 0;
  for (const it of items) {
    if (cur.length && (size + it.length + 2 > LIMIT - overhead || size >= target)) { out.push(render(cur)); cur = []; size = 0; }
    cur.push(it); size += it.length + 2;
  }
  if (cur.length) out.push(render(cur));
  return out;
};
// The texts travel as base64 JSON (only letters, digits, + / =, in short lines), because the Supabase SQL editor
// mangled long plain-text values (quotes, semicolons and words like "from a" inside them) on the way in. The
// database decodes them and writes exactly the same values as 04-catalogue.sql.
const exJson = cat.exercises.map((e) => {
  const img = e.media?.images?.[0];
  const s = (v) => (v == null ? null : String(v));
  const a = (v) => (Array.isArray(v) ? v.map(String) : []);
  return JSON.stringify({ r: e.id, n: s(e.name), a: a(e.aliases), c: s(e.category), t: s(e.tracking), d: s(e.description), s: a(e.setup), st: a(e.steps),
    cu: a(e.cues), m: a(e.mistakes), u: img ? '/catalogue/app_media/' + img.path : null, cr: s(img?.source_url ?? null), l: s(img?.license ?? null) });
});
const b64 = (items) => Buffer.from('[' + items.join(',') + ']', 'utf8').toString('base64').match(/.{1,100}/g).join('\n');
const arrOf = (k) => `array(select jsonb_array_elements_text(e->'${k}'))`;
const exSql = (items) => `insert into diary.exercises (id, source, source_ref, name, aliases, category, tracking, description, setup, steps, cues, mistakes, media_url, credit, licence)
select md5('mfd:' || (e->>'r'))::uuid, 'mfd', e->>'r', e->>'n', ${arrOf('a')}, e->>'c', e->>'t', e->>'d',
  ${arrOf('s')}, ${arrOf('st')}, ${arrOf('cu')}, ${arrOf('m')}, e->>'u', e->>'cr', e->>'l'
from jsonb_array_elements(convert_from(decode(translate('
${b64(items)}
', E' \\n\\r', ''), 'base64'), 'UTF8')::jsonb) e
${exTail}`;
// base64 is 4/3 the size of the JSON, plus a newline every 100 characters.
const ex = chunks(exJson.map((j) => ({ j, length: Math.ceil(Buffer.byteLength(j) * 1.37) })), (items) => exSql(items.map((x) => x.j)), 2000);
const linkItems = links.flatMap(({ t, cols, rs }) => rs.map((r) => ({ t, cols, r, length: r.length })));
const linkSql = (items) => {
  const byT = [];
  for (const it of items) { const last = byT[byT.length - 1]; if (last && last.t === it.t) last.rs.push(it.r); else byT.push({ t: it.t, cols: it.cols, rs: [it.r] }); }
  return byT.map(({ t, cols, rs }) => {
    const vs = cols.slice(1).map((_, i) => 'c' + i);
    return `insert into diary.${t} (${cols.join(', ')})\nselect md5('mfd:' || v.ref)::uuid, ${vs.map((c) => 'v.' + c).join(', ')} from (values\n${rs.join(',\n')}\n) v(ref, ${vs.join(', ')})\non conflict do nothing;`;
  }).join('\n');
};
const lk = chunks(linkItems, (items) => linkSql(items), 2000);
const n = 1 + ex.length + lk.length;
ex.forEach((sql, i) => files.push([`${files.length + 1}-library-texts`, wrap(`file ${files.length + 1} of ${n}: exercise texts (${i + 1}/${ex.length})`, sql)]));
lk.forEach((sql, i) => files.push([`${files.length + 1}-library-links`, wrap(`file ${files.length + 1} of ${n}: exercise muscles and equipment (${i + 1}/${lk.length})`, sql)]));
files[0][1] = files[0][1].replace('file 1:', `file 1 of ${n}:`);

const dir = process.argv[2] || path.join(os.homedir(), 'Downloads', 'mfd-db-install');
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });
for (const [name, sql] of files) {
  fs.writeFileSync(path.join(dir, name + '.sql'), sql);
  console.log(`${name}.sql: ${(sql.length / 1024).toFixed(0)} KB`);
}
