// Writes ~/Downloads/mfd-backup-setup[-staging].sql: database/backup/backup.sql plus this install's setup values,
// then builds the first backup and shows a short report. Run once per database (safe to run again: same token).
//   * the public key: database/backup/public-key.asc (the private key and its passphrase stay on the owner's Mac);
//   * the fetch token: random, kept in the macOS Keychain ("MFD backup token" / "... (staging)"); only its SHA-256
//     goes into the file. The Google script needs the token itself: copy it from the Keychain when setting it up.
// Usage: node scripts-backup-setup.cjs [--staging]
const fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto'), {execFileSync} = require('child_process');
const staging = process.argv.includes('--staging');
const service = 'MFD backup token' + (staging ? ' (staging)' : '');
let token;
try { token = execFileSync('security', ['find-generic-password', '-s', service, '-a', 'mfd-backups', '-w'], {encoding: 'utf8'}).trim(); }
catch { token = crypto.randomBytes(32).toString('base64url'); execFileSync('security', ['add-generic-password', '-U', '-s', service, '-a', 'mfd-backups', '-w', token]); }
const hash = crypto.createHash('sha256').update(token).digest('hex');
const key = fs.readFileSync(path.join(__dirname, 'database/backup/public-key.asc'), 'utf8').trim();
if (!/^-----BEGIN PGP PUBLIC KEY BLOCK-----[\s\S]+-----END PGP PUBLIC KEY BLOCK-----$/.test(key)) throw new Error('public-key.asc is not an armored public key');
const sql = fs.readFileSync(path.join(__dirname, 'database/backup/backup.sql'), 'utf8');
const out = `-- MFD weekly encrypted backup: install${staging ? ' (STAGING)' : ''}. Paste all of it into the Supabase SQL editor and press Run.
-- Generated by scripts-backup-setup.cjs. Holds only the PUBLIC key and the token's SHA-256 (no secrets).
${sql}
insert into mfd_backup.settings (id, public_key, token_sha256) values (true, $key$${key}$key$, decode('${hash}', 'hex'))
  on conflict (id) do update set public_key = excluded.public_key, token_sha256 = excluded.token_sha256;
select mfd_backup.build() as first_backup;
select f.id, f.created_at, f.tables, f.rows, pg_size_pretty(f.plain_bytes) as data_size, pg_size_pretty(octet_length(f.data)::bigint) as locked_size,
       (select count(*) from cron.job where jobname = 'mfd-weekly-backup') as weekly_job
from mfd_backup.files f order by f.id desc limit 1;
`;
const file = path.join(os.homedir(), 'Downloads', `mfd-backup-setup${staging ? '-staging' : ''}.sql`);
fs.writeFileSync(file, out);
console.log(`${file}: ${(out.length / 1024).toFixed(0)} KB; token in Keychain "${service}"`);
