// Writes database/diary/04-catalogue.sql from the app's built-in exercise catalogue
// (public/catalogue/mfd_exercises.json): muscle groups, muscles, equipment, and every exercise with its muscle groups,
// muscles and equipment, as shared library rows (user_id empty, source 'mfd', source_ref = the catalogue id).
// Re-running the SQL updates existing rows in place; ids never change, so routines and workouts keep pointing at them.
// Usage: node scripts-diary-catalogue.cjs
const fs = require('fs');
const cat = JSON.parse(fs.readFileSync('public/catalogue/mfd_exercises.json', 'utf8'));
const q = (v) => (v == null ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (a) => (Array.isArray(a) && a.length ? 'array[' + a.map(q).join(',') + ']::text[]' : "'{}'::text[]");
const rows = (list) => list.join(',\n');
const m = cat.meta;

let out = `-- Generated by scripts-diary-catalogue.cjs from ${m.name} ${m.version} (${cat.exercises.length} exercises). Do not edit by hand.
-- MFD 3.0 database, part 4: the built-in exercise library. Run after 02-library.sql. Safe to re-run.
begin;

insert into diary.muscle_groups (key, name) values
${rows(Object.entries(m.groups).map(([k, v]) => `(${q(k)}, ${q(v)})`))}
on conflict (key) do update set name = excluded.name;

insert into diary.muscles (key, name, muscle_group) values
${rows(Object.entries(m.muscles).map(([k, v]) => `(${q(k)}, ${q(v.name)}, ${q(v.group)})`))}
on conflict (key) do update set name = excluded.name, muscle_group = excluded.muscle_group;

insert into diary.equipment (key, name) values
${rows(Object.entries(m.equipment).map(([k, v]) => `(${q(k)}, ${q(v)})`))}
on conflict (key) do update set name = excluded.name;

-- One fixed id per built-in exercise (from its catalogue id), so this file can run again without new ids.
insert into diary.exercises (id, source, source_ref, name, aliases, category, tracking, description, setup, steps, cues, mistakes, media_url, credit, licence) values
`;
out += rows(cat.exercises.map((e) => {
  const img = e.media?.images?.[0];
  return `(md5('mfd:' || ${q(e.id)})::uuid, 'mfd', ${q(e.id)}, ${q(e.name)}, ${arr(e.aliases)}, ${q(e.category)}, ${q(e.tracking)}, ${q(e.description)}, ${arr(e.setup)}, ${arr(e.steps)}, ${arr(e.cues)}, ${arr(e.mistakes)}, ${q(img ? '/catalogue/app_media/' + img.path : null)}, ${q(img?.source_url ?? null)}, ${q(img?.license ?? null)})`;
}));
out += `
on conflict (source, source_ref) where user_id is null do update set
  name = excluded.name, aliases = excluded.aliases, category = excluded.category, tracking = excluded.tracking,
  description = excluded.description, setup = excluded.setup, steps = excluded.steps, cues = excluded.cues,
  mistakes = excluded.mistakes, media_url = excluded.media_url, credit = excluded.credit, licence = excluded.licence;

-- Links: replaced as a whole for the built-in exercises.
delete from diary.exercise_muscle_groups where exercise_id in (select id from diary.exercises where source = 'mfd' and user_id is null);
delete from diary.exercise_muscles where exercise_id in (select id from diary.exercises where source = 'mfd' and user_id is null);
delete from diary.exercise_equipment where exercise_id in (select id from diary.exercises where source = 'mfd' and user_id is null);
`;
const link = (table, col, list) => list.length ? `insert into diary.${table} (exercise_id, ${col}${table === 'exercise_equipment' ? '' : ', role'}) values\n${rows(list)}\non conflict do nothing;\n` : '';
const groups = [], muscles = [], equipment = [];
for (const e of cat.exercises) {
  const id = `md5('mfd:' || ${q(e.id)})::uuid`;
  const seenG = new Set();
  for (const role of ['primary', 'secondary']) for (const g of e.muscle_groups?.[role] ?? []) if (!seenG.has(g)) { seenG.add(g); groups.push(`(${id}, ${q(g)}, '${role}')`); }
  const seenM = new Set();
  for (const [role, key] of [['primary', 'primary'], ['secondary', 'secondary'], ['stabiliser', 'stabilizers']]) for (const mu of e.muscles?.[key] ?? []) if (!seenM.has(mu)) { seenM.add(mu); muscles.push(`(${id}, ${q(mu)}, '${role}')`); }
  for (const k of new Set(e.equipment ?? [])) equipment.push(`(${id}, ${q(k)})`);
}
out += link('exercise_muscle_groups', 'muscle_group', groups) + link('exercise_muscles', 'muscle', muscles) + link('exercise_equipment', 'equipment', equipment);
out += 'commit;\n';
fs.writeFileSync('database/diary/04-catalogue.sql', out);
console.log(`database/diary/04-catalogue.sql: ${cat.exercises.length} exercises, ${groups.length} muscle-group links, ${muscles.length} muscle links, ${equipment.length} equipment links, ${(out.length / 1024).toFixed(0)} KB`);
