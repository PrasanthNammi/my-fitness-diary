// Writes ~/Downloads/mfd-db-lossless-check.sql: step 2a's proof on the real diaries, changing nothing.
// In one transaction that ends with an error carrying the report (so everything is undone): installs the "extra"
// columns and the new copy/rebuild code (02-library, 03-training, 05-fill-training, 12-read), refills every diary's
// training, then compares, per person, the training rebuilt from the tables with the stored diary, EXACTLY (as JSON:
// every value, every empty value, list order). Every line should say EXACT.
// Usage: node scripts-diary-lossless-check.cjs [out-file]
const fs = require('fs'), os = require('os'), path = require('path');
const strip = (sql) => sql.split('\n').filter((l) => !/^\s*(begin|commit);\s*$/i.test(l)).join('\n');
const part = (f) => strip(fs.readFileSync(path.join(__dirname, 'database/diary', f + '.sql'), 'utf8'));
const out = `-- Database move, step 2a: does every diary's training come back EXACTLY from the tables? Changes nothing.
-- Paste all of it into the Supabase SQL editor (project Forma) and press Run; the "error" shown is the report.
-- Generated by scripts-diary-lossless-check.cjs from database/diary/02, 03, 05 and 12.
begin;
${part('02-library')}
${part('03-training')}
${part('05-fill-training')}
${part('12-read')}
do $fill$ declare u uuid; begin
  for u in select user_id from public.forma_workspaces loop perform diary.fill_training(u); end loop;
end $fill$;
do $chk$
declare r record; rep text := ''; k text; n_items int; n_diff int; ex text; o jsonb; b jsonb; people int := 0; bad int := 0;
begin
  for r in select f.user_id, f.payload p, diary.training_json(f.user_id) t, row_number() over (order by f.user_id) i from public.forma_workspaces f loop
    people := people + 1;
    foreach k in array array['sessions', 'active', 'folders', 'routines', 'mfdExercises'] loop
      o := r.p->k; b := r.t->k;
      if jsonb_typeof(o) = 'array' and jsonb_typeof(b) = 'array' then
        select count(*), count(*) filter (where oo.v is distinct from bb.v), min(coalesce(oo.v->>'id', bb.v->>'id', oo.v->>'name', bb.v->>'name')) filter (where oo.v is distinct from bb.v)
          into n_items, n_diff, ex
        from (select v, i from jsonb_array_elements(o) with ordinality x(v, i)) oo full join (select v, i from jsonb_array_elements(b) with ordinality x(v, i)) bb using (i);
      else
        n_items := case when o is null and b is null then 0 else 1 end; n_diff := case when o is distinct from b then 1 else 0 end; ex := null;
        -- (no running workout: the stored diary has "active": null, which is the same; a list the diary doesn't have at
        -- all comes back empty: whether the list exists is kept by the switch in step 2b)
        if coalesce(o, 'null'::jsonb) = coalesce(b, 'null'::jsonb) or (o is null and b = '[]'::jsonb) then n_diff := 0; end if;
      end if;
      if n_diff > 0 then bad := bad + 1; end if;
      rep := rep || rpad('person ' || r.i, 10) || rpad(k, 14) || lpad(n_items::text, 7) || lpad(n_diff::text, 7) || '  '
        || case when n_diff = 0 then 'EXACT' else 'DIFFERENT' || coalesce(' (e.g. ' || left(ex, 40) || ')', '') end || chr(10);
    end loop;
  end loop;
  raise exception '%', 'STEP 2a CHECK · the "error" is on purpose: everything is undone.' || chr(10)
    || people || ' diaries · ' || case when bad = 0 then 'ALL EXACT' else bad || ' line(s) DIFFERENT' end
    || ' · problems noted while copying: ' || (select count(*) from diary.fill_problems where kind = 'error') || chr(10) || chr(10)
    || rpad('Who', 10) || rpad('What', 14) || lpad('items', 7) || lpad('diff', 7) || chr(10) || rep;
end $chk$;
`;
const file = process.argv[2] || path.join(os.homedir(), 'Downloads', 'mfd-db-lossless-check.sql');
fs.writeFileSync(file, out);
console.log(`${file}: ${(out.length / 1024).toFixed(0)} KB`);
